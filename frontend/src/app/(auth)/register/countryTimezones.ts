/**
 * Returns the primary IANA timezone for a given country name.
 * Defaults to 'UTC' if not found.
 */
export function getTimezoneForCountry(country: string): string {
  if (!country) return 'UTC';
  return COUNTRY_TO_TIMEZONE[country.trim()] || 'UTC';
}

/**
 * Formats a clean display label for any IANA timezone using Intl.DateTimeFormat
 */
export function formatTimezoneDisplay(tz: string): string {
  const existing = POPULAR_TIMEZONES.find((t) => t.value === tz);
  if (existing) return existing.label;

  try {
    const offset = new Intl.DateTimeFormat('en-US', {
      timeZone: tz,
      timeZoneName: 'shortOffset',
    })
      .formatToParts(new Date())
      .find((p) => p.type === 'timeZoneName')?.value;

    return offset ? `${tz} (${offset})` : tz;
  } catch {
    return tz;
  }
}

/**
 * Builds the complete list of timezone options, ensuring the currently selected
 * timezone is always present and properly labeled.
 */
export function getTimezoneOptions(selectedTimezone?: string): { value: string; label: string }[] {
  const options = [...POPULAR_TIMEZONES];
  if (selectedTimezone && !options.some((o) => o.value === selectedTimezone)) {
    options.unshift({
      value: selectedTimezone,
      label: formatTimezoneDisplay(selectedTimezone),
    });
  }
  return options;
}

/**
 * Tries to find a matching country for a given IANA timezone string.
 */
export function getCountryForTimezone(tz: string): string | null {
  if (!tz) return null;
  const lower = tz.toLowerCase();
  for (const [country, timeZone] of Object.entries(COUNTRY_TO_TIMEZONE)) {
    if (timeZone.toLowerCase() === lower) {
      return country;
    }
  }
  if (lower.startsWith('america/')) return 'United States';
  if (lower.startsWith('australia/')) return 'Australia';
  return null;
}

